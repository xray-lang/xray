#!/usr/bin/env python3
"""Embed stdlib/types/*.xr files into a C header as string literals.

Usage:
  python3 scripts/embed_native_types.py stdlib/types/
  python3 scripts/embed_native_types.py stdlib/types/ --output path/to/xnative_type_defs.inc.c
  python3 scripts/embed_native_types.py stdlib/types/ --check path/to/xnative_type_defs.inc.c

The generated file provides:
  - XR_NATIVE_TYPE_DEFS: X-macro list of (name, source_string)
  - Individual static const char *xr_native_def_XXX strings
"""

import argparse
import glob
import os
import sys

def escape_c_string(s):
    """Escape a string for embedding as a C string literal."""
    result = []
    for ch in s:
        if ch == '\\':
            result.append('\\\\')
        elif ch == '"':
            result.append('\\"')
        elif ch == '\n':
            result.append('\\n')
        elif ch == '\t':
            result.append('\\t')
        else:
            result.append(ch)
    return ''.join(result)

def render(types_dir):
    xr_files = sorted(glob.glob(os.path.join(types_dir, "*.xr")))

    if not xr_files:
        raise ValueError(f"No .xr files found in {types_dir}")

    lines = ["/* Auto-generated by scripts/embed_native_types.py — DO NOT EDIT */", ""]

    entries = []
    for path in xr_files:
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
        var_name = f"xr_native_def_{name}"
        escaped = escape_c_string(content)
        lines.extend([f'static const char {var_name}[] = "{escaped}";', ""])
        entries.append((name, var_name))

    # Generate X-macro list
    lines.append("#define XR_NATIVE_TYPE_DEFS(X) \\")
    for i, (name, var_name) in enumerate(entries):
        suffix = " \\" if i < len(entries) - 1 else ""
        lines.append(f'    X("{name}", {var_name}){suffix}')
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("types_dir")
    output_group = parser.add_mutually_exclusive_group()
    output_group.add_argument("--output")
    output_group.add_argument("--check")
    args = parser.parse_args()

    try:
        generated = render(args.types_dir)
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1

    if args.check:
        try:
            with open(args.check, "r", encoding="utf-8") as generated_file:
                current = generated_file.read()
        except OSError as exc:
            print(f"cannot read generated native type table: {exc}", file=sys.stderr)
            return 1
        if current != generated:
            print(
                f"generated native type table is stale: run {sys.executable} "
                f"{os.path.relpath(__file__)} {args.types_dir} --output {args.check}",
                file=sys.stderr,
            )
            return 1
        return 0

    if args.output:
        with open(args.output, "w", encoding="utf-8") as generated_file:
            generated_file.write(generated)
    else:
        sys.stdout.write(generated)
    return 0

if __name__ == "__main__":
    sys.exit(main())
