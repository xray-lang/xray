@dataclass
class IselEntry:
    xm_op: str      # e.g. "ADD"
    target: str     # "x64", "arm64", "riscv64"
    pattern: str    # "GP_RRR", "CUSTOM", etc.
    mcinsn: str     # primary machine instruction(s)
    notes: str      # optional notes

VALID_ISEL_PATTERNS = {
    'GP_RR_COMM', 'GP_RR', 'GP_RRR', 'GP_R',
    'FP_RR_COMM', 'FP_RR', 'FP_RRR', 'FP_R',
    'CMP_RR_CC', 'FCMP_RR_CC',
    'CONV', 'MEM_LOAD', 'MEM_STORE',
    'CALL_HELPER', 'CUSTOM',
}

VALID_ISEL_TARGETS = {'x64', 'arm64', 'riscv64'}

def parse_isel_def(text: str) -> list[IselEntry]:
    entries = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        m = re.match(
            r'ISEL\(\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*([^,)]+)'
            r'(?:\s*,\s*"([^"]*)")?\s*\)',
            line)
        if not m:
            continue
        xm_op, target, pattern, mcinsn, notes = m.groups()
        entries.append(IselEntry(
            xm_op=xm_op, target=target.strip(),
            pattern=pattern.strip(), mcinsn=mcinsn.strip(),
            notes=notes or ''))
    return entries

def _split_isel_mcinsns(s: str) -> list[str]:
    """Split a mcinsn field like 'x64.cmp.rr+x64.setcc' into its components.
    Returns the list of concrete mcinsn names, dropping the '-' placeholder.
    """
    out: list[str] = []
    for chunk in s.replace(',', '+').split('+'):
        chunk = chunk.strip()
        if chunk and chunk != '-':
            out.append(chunk)
    return out

def validate_isel(entries: list[IselEntry], ops: list[OpDef],
                  arch_mcinsns: Optional[dict[str, set[str]]] = None) -> list[str]:
    """Validate isel.def against ops.def and (optionally) per-arch mcinsn sets.

    When `arch_mcinsns` is supplied (mapping target -> set of real mcinsn names
    from the corresponding `xisa/arch/<target>.isa`), every non-placeholder
    mcinsn reference in `isel.def` must resolve to a real mcinsn for that arch.
    The '-' placeholder is allowed (used for CUSTOM lowering or for entries
    where no dedicated mcinsn exists yet).
    """
    errors = []
    op_names = {o.name for o in ops}

    for e in entries:
        if e.xm_op not in op_names:
            errors.append(f"ISEL references unknown op XM_{e.xm_op}")
        if e.target not in VALID_ISEL_TARGETS:
            errors.append(f"ISEL({e.xm_op}, {e.target}): unknown target")
        if e.pattern not in VALID_ISEL_PATTERNS:
            errors.append(f"ISEL({e.xm_op}, {e.target}): unknown pattern '{e.pattern}'")
        if arch_mcinsns is not None and e.target in arch_mcinsns:
            for m in _split_isel_mcinsns(e.mcinsn):
                if m not in arch_mcinsns[e.target]:
                    errors.append(
                        f"ISEL({e.xm_op}, {e.target}): mcinsn '{m}' "
                        f"is not defined in xisa/arch/{e.target}.isa")

    # Check coverage: every op should have entries for all 3 targets
    covered = {}
    for e in entries:
        covered.setdefault(e.xm_op, set()).add(e.target)
    for op in ops:
        targets = covered.get(op.name, set())
        for t in VALID_ISEL_TARGETS:
            if t not in targets:
                errors.append(f"XM_{op.name} missing ISEL entry for target '{t}'")

    return errors

def isel_coverage_report(entries: list[IselEntry], ops: list[OpDef]) -> str:
    """Generate a human-readable coverage report."""
    lines = []
    lines.append(f'isel coverage: {len(entries)} entries, {len(ops)} ops, '
                 f'{len(VALID_ISEL_TARGETS)} targets')

    # Count patterns
    pattern_counts: dict[str, int] = {}
    custom_count = 0
    for e in entries:
        pattern_counts[e.pattern] = pattern_counts.get(e.pattern, 0) + 1
        if e.pattern == 'CUSTOM':
            custom_count += 1
    non_custom = len(entries) - custom_count
    lines.append(f'  patterned: {non_custom}, custom: {custom_count}')

    # Per-target summary
    for t in sorted(VALID_ISEL_TARGETS):
        t_entries = [e for e in entries if e.target == t]
        t_custom = sum(1 for e in t_entries if e.pattern == 'CUSTOM')
        lines.append(f'  {t}: {len(t_entries)} entries ({t_custom} custom)')

    return '\n'.join(lines)

def generate_dispatch_coverage_header(entries: list[IselEntry]) -> str:
    """Generate xm_dispatch_coverage_gen.h: per-backend XmOp coverage manifests.

    The header declares X-macros that the JIT backends and CI checker use as the
    single source of truth for "which XmOps each backend is required to handle".
    The generator emits one X-macro per backend; CI scripts read this file to
    diff against the actual handler tables and detect drift in either direction.
    """
    by_target: dict[str, list[str]] = {t: [] for t in sorted(VALID_ISEL_TARGETS)}
    seen: dict[str, set[str]] = {t: set() for t in by_target}
    for e in entries:
        if e.target not in by_target:
            continue
        if e.xm_op in seen[e.target]:
            continue
        seen[e.target].add(e.xm_op)
        by_target[e.target].append(e.xm_op)

    lines = []
    lines.append('/* AUTO-GENERATED by xisagen — DO NOT EDIT */')
    lines.append('/* Source: xisa/xm/isel.def */')
    lines.append('')
    lines.append('#ifndef XM_DISPATCH_COVERAGE_GEN_H')
    lines.append('#define XM_DISPATCH_COVERAGE_GEN_H')
    lines.append('')
    lines.append('/* Per-backend XmOp coverage declared in isel.def.')
    lines.append(' * Use via:  #define VISIT(op) ... XM_DISPATCH_<BE>(VISIT) #undef VISIT')
    lines.append(' * Consumed by CI dispatch-coverage check. */')
    lines.append('')

    macro_for = {'x64': 'XM_DISPATCH_X64',
                 'arm64': 'XM_DISPATCH_ARM64',
                 'riscv64': 'XM_DISPATCH_RISCV64'}
    for target in ('x64', 'arm64', 'riscv64'):
        ops = by_target.get(target, [])
        lines.append(f'/* {target}: {len(ops)} ops declared in isel.def */')
        lines.append(f'#define {macro_for[target]}(X) \\')
        for i, op in enumerate(ops):
            sep = ' \\' if i + 1 < len(ops) else ''
            lines.append(f'    X({op}){sep}')
        lines.append('')

    lines.append('#endif  /* XM_DISPATCH_COVERAGE_GEN_H */')
    lines.append('')
    return '\n'.join(lines)

