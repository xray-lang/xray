# ============================================================
# External assembler diff (llvm-mc): independent verification
# ============================================================
#
# For each (regs, asm) row in :golden-asm we ask llvm-mc to assemble
# the canonical mnemonic and compare its encoding bytes to the matching
# :golden-bytes row. This is the strongest external truth source we
# have for the .isa: a typo in either spec or golden bytes would have
# to also exist in llvm-mc to slip past this check.

_LLVM_MC_TRIPLE = {
    'arm64':   'aarch64',
    'x64':     'x86_64',
    'riscv64': 'riscv64',
}

# Architecture extensions that must be enabled for llvm-mc to recognise
# all the canonical mnemonics we use in :golden-asm.
_LLVM_MC_MATTR = {
    'arm64':   '',
    'x64':     '',
    'riscv64': '+m,+a,+f,+d,+zicsr',
}

# mcinsns that llvm-mc handles with a *different* (usually shorter) but
# semantically-equivalent encoding. Our .isa intentionally pins the wider
# variant for codegen reasons (e.g. JIT forward-patches need a fixed size).
# Each entry skips the llvm-mc cross-check for that mcinsn alone — the
# inline-emit and golden-bytes round-trip already covers them.
_LLVM_MC_SKIP_MCINSNS = {
    # x86: imm/disp width pinning. llvm-mc picks ri8 / disp8 / accumulator
    # special form when the value fits; we use the wider form to keep the
    # instruction length stable for back-patching.
    'x64.add.ri32',  'x64.sub.ri32',  'x64.and.ri32',
    'x64.or.ri32',   'x64.cmp.ri32',  'x64.test.ri32',
    'x64.load.bd32', 'x64.store.bd32', 'x64.lea.bd32',
    'x64.shr.ri',  # llvm-mc shortens 'shr r, 1' to the special D1/E8 form.
    # Relative-branch instructions: llvm-mc cannot assemble a numeric
    # offset standalone, only via labels. The .isa golden bytes for these
    # are 0-target placeholders patched at JIT time anyway.
    'x64.jmp.rel8',  'x64.jmp.rel32', 'x64.call.rel32', 'x64.jcc.rel32',
}


def _x86_intel_inject_ptr(asm: str) -> str:
    """Inject `ptr` after byte/word/dword/qword size keywords for llvm-mc."""
    import re
    # Match a size keyword followed by space(s) and `[` (memory operand),
    # but only when the next token isn't already `ptr`. Simpler: match
    # `<size> [` (no `ptr`) and replace with `<size> ptr [`.
    return re.sub(
        r'\b(byte|word|dword|qword)\s+\[',
        r'\1 ptr [',
        asm,
        flags=re.IGNORECASE)


def _llvm_mc_assemble(llvm_mc_path: str, arch: str, asm: str):
    """Run llvm-mc on a single asm line. Returns (bytes_list, error_msg)."""
    import subprocess
    triple = _LLVM_MC_TRIPLE[arch]
    mattr = _LLVM_MC_MATTR.get(arch, '')
    if arch == 'x64':
        # Intel syntax for x86: prepend the directive AND inject `ptr` after
        # size keywords so llvm-mc parses the same dialect we use in :golden-asm.
        asm_text = '.intel_syntax noprefix\n' + _x86_intel_inject_ptr(asm) + '\n'
    else:
        asm_text = asm + '\n'
    cmd = [llvm_mc_path, f'--triple={triple}', '--assemble', '--show-encoding']
    if mattr:
        cmd.append(f'--mattr={mattr}')
    try:
        result = subprocess.run(
            cmd, input=asm_text, capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.TimeoutExpired) as e:
        return None, f'llvm-mc failed: {e}'
    if result.returncode != 0:
        return None, f'llvm-mc rc={result.returncode}: {result.stderr.strip()}'
    # Parse "encoding: [0xab,0xcd,...]" from stdout.
    import re
    m = re.search(r'encoding:\s*\[([^\]]*)\]', result.stdout)
    if not m:
        return None, f'no encoding line in llvm-mc output: {result.stdout!r}'
    parts = [p.strip() for p in m.group(1).split(',') if p.strip()]
    bytes_list = []
    for p in parts:
        try:
            bytes_list.append(int(p, 0))
        except ValueError:
            return None, f'cannot parse byte {p!r} in llvm-mc output'
    return bytes_list, None


def _hex_str_to_bytes(hex_str: str):
    parts = hex_str.split()
    out = []
    for p in parts:
        try:
            out.append(int(p, 16))
        except ValueError:
            return None
    return out


def cmd_llvm_mc_check(args: list[str]):
    """Cross-validate every :golden-asm row against llvm-mc.

    Usage: xisagen llvm-mc-check [--llvm-mc=<path>] arm64=<isa> x64=<isa> ...

    Soft-skips with exit 0 when llvm-mc is unavailable, to keep CI green
    on hosts that don't ship llvm. When llvm-mc IS available, any byte
    mismatch is a hard failure.
    """
    import shutil
    llvm_mc_path = None
    arch_specs = []
    for a in args:
        if a.startswith('--llvm-mc='):
            llvm_mc_path = a.split('=', 1)[1]
        elif '=' in a:
            arch_specs.append(a)
        else:
            die(f'unexpected arg {a!r}; expected arch=<isa> or --llvm-mc=<path>')
    if not arch_specs:
        die('usage: xisagen llvm-mc-check [--llvm-mc=<path>] arch=<isa> [...]')
    if llvm_mc_path is None:
        llvm_mc_path = shutil.which('llvm-mc')
        if llvm_mc_path is None:
            for p in ('/opt/homebrew/opt/llvm/bin/llvm-mc',
                      '/usr/local/opt/llvm/bin/llvm-mc'):
                if os.path.isfile(p) and os.access(p, os.X_OK):
                    llvm_mc_path = p
                    break
    if llvm_mc_path is None or not os.path.isfile(llvm_mc_path):
        print('xisagen llvm-mc-check: llvm-mc not found, skipping (soft-pass)',
              file=sys.stderr)
        return
    print(f'xisagen llvm-mc-check: using {llvm_mc_path}', file=sys.stderr)

    total_checked = 0
    total_mismatch = 0
    total_skipped_unmatched = 0
    total_skipped_listed = 0
    for spec in arch_specs:
        arch, path = spec.split('=', 1)
        if arch not in _LLVM_MC_TRIPLE:
            die(f'llvm-mc-check: unsupported arch {arch!r}')
        _regclasses, mcinsns = load_isa(path)
        n_checked = 0
        n_mismatch = 0
        n_unmatched = 0
        n_skipped = 0
        for insn in mcinsns:
            if insn.name in _LLVM_MC_SKIP_MCINSNS:
                n_skipped += 1
                continue
            # Build a regs-keyed map of declared bytes for matching.
            bytes_by_regs = {}
            for regs, hex_str in insn.golden_bytes:
                bytes_by_regs[tuple(regs)] = hex_str
            for regs, asm in insn.golden_asm:
                key = tuple(regs)
                if key not in bytes_by_regs:
                    # No matching bytes row — defensive skip; would already
                    # be flagged by the .isa structural validator.
                    n_unmatched += 1
                    continue
                expected = _hex_str_to_bytes(bytes_by_regs[key])
                if expected is None:
                    n_unmatched += 1
                    continue
                got, err = _llvm_mc_assemble(llvm_mc_path, arch, asm)
                if got is None:
                    print(f'  LLVM-MC-ERROR: {insn.name} regs={regs} asm={asm!r}: {err}',
                          file=sys.stderr)
                    n_mismatch += 1
                    continue
                n_checked += 1
                if got != expected:
                    print(f'  LLVM-MC-MISMATCH: {insn.name} regs={regs}: '
                          f'asm={asm!r} expected={" ".join(f"{b:02x}" for b in expected)} '
                          f'got={" ".join(f"{b:02x}" for b in got)}',
                          file=sys.stderr)
                    n_mismatch += 1
        total_checked += n_checked
        total_mismatch += n_mismatch
        total_skipped_unmatched += n_unmatched
        total_skipped_listed += n_skipped
        print(f'xisagen llvm-mc-check: {arch}: {n_checked} verified, '
              f'{n_mismatch} mismatched, {n_unmatched} unmatched-asm, '
              f'{n_skipped} skipped (encoding-pinned)',
              file=sys.stderr)
    if total_mismatch:
        die(f'llvm-mc-check: {total_mismatch} mismatch(es) — .isa or '
            f'llvm-mc disagree on encoding')
    print(f'xisagen llvm-mc-check: ok ({total_checked} rows verified, '
          f'{total_skipped_listed} encoding-pinned skipped, across '
          f'{len(arch_specs)} arch(es))', file=sys.stderr)


