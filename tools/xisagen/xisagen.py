@dataclass
class HelperDef:
    name: str       # e.g. "call_func"
    nargs: int
    ret_rep: str    # "TAGGED", "PTR", "I64", "F64", "VOID"
    flags: list     # ["GC", "DEOPT", ...]

def parse_helpers_def(text: str) -> list[HelperDef]:
    helpers = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        m = re.match(r'XM_HELPER\(\s*(\w+)\s*,\s*(\d+)\s*,\s*(\w+)\s*,\s*([^)]*)\)', line)
        if not m:
            continue
        name, nargs, ret_rep, flags_str = m.groups()
        flags = [f.strip() for f in flags_str.split('|') if f.strip() and f.strip() != 'NONE']
        helpers.append(HelperDef(name=name, nargs=int(nargs), ret_rep=ret_rep, flags=flags))
    return helpers

def generate_helpers_header(helpers: list[HelperDef]) -> str:
    lines = []
    lines.append('/* AUTO-GENERATED by xisagen — DO NOT EDIT */')
    lines.append('/* Source: xisa/xm/helpers.def */')
    lines.append('')
    lines.append('#ifndef XM_HELPERS_GEN_H')
    lines.append('#define XM_HELPERS_GEN_H')
    lines.append('')
    lines.append('#include <stdint.h>')
    lines.append('#include <stdbool.h>')
    lines.append('')

    # Flag defines
    lines.append('/* ========== Helper Flags ========== */')
    lines.append('')
    lines.append('#define XM_HF_GC      (1 << 0)')
    lines.append('#define XM_HF_DEOPT   (1 << 1)')
    lines.append('#define XM_HF_THROW   (1 << 2)')
    lines.append('#define XM_HF_SUSPEND (1 << 3)')
    lines.append('')

    # Helper ID enum
    lines.append('/* ========== Helper IDs ========== */')
    lines.append('')
    lines.append('typedef enum {')
    for i, h in enumerate(helpers):
        lines.append(f'    XM_HELPER_{h.name} = {i},')
    lines.append(f'    XM_HELPER__COUNT')
    lines.append('} XmHelperId;')
    lines.append('')

    # Metadata struct
    lines.append('/* ========== Helper Metadata ========== */')
    lines.append('')
    lines.append('typedef struct {')
    lines.append('    void *func;       /* C function pointer (set by xm_helper_table.c) */')
    lines.append('    uint8_t ret_rep;  /* XrRep: return representation */')
    lines.append('    uint8_t nargs;    /* call_arg_pool arguments consumed */')
    lines.append('    uint16_t flags;   /* XM_HF_* */')
    lines.append('} XmHelperInfo;')
    lines.append('')

    # Static metadata table
    lines.append('/* ========== Helper Metadata Table (static, no func ptr) ========== */')
    lines.append('')
    lines.append('#ifdef XM_HELPERS_META_IMPL')
    lines.append('static const struct { uint8_t ret_rep; uint8_t nargs; uint16_t flags; } xm_helper_meta[XM_HELPER__COUNT] = {')
    for h in helpers:
        flags_expr = ' | '.join(f'XM_HF_{f}' for f in h.flags) if h.flags else '0'
        lines.append(f'    [XM_HELPER_{h.name}] = {{ XR_REP_{h.ret_rep}, {h.nargs}, {flags_expr} }},')
    lines.append('};')
    lines.append('#endif')
    lines.append('')

    # X-macro for fn-ptr table
    lines.append('/* ========== X-Macro for fn-ptr table ========== */')
    lines.append('')
    lines.append('#define XM_HELPER_DEF(_) \\')
    for i, h in enumerate(helpers):
        flags_expr = ' | '.join(f'XM_HF_{f}' for f in h.flags) if h.flags else '0'
        cont = ' \\' if i < len(helpers) - 1 else ''
        lines.append(f'    _({h.name}, {h.nargs}, XR_REP_{h.ret_rep}, {flags_expr}){cont}')
    lines.append('')

    lines.append('#endif  // XM_HELPERS_GEN_H')
    lines.append('')
    return '\n'.join(lines)

