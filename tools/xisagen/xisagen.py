# L5: Typecheck — validate .isa internal consistency
# ============================================================

@dataclass
class IsaDiag:
    level: str   # "error" or "warn"
    insn: str
    msg: str

VALID_EXTERNAL_REFERENCES = {
    'llvm-mc',     # LLVM `llvm-mc` machine-code tool
    'gnu-as',      # GNU assembler (gas)
    'objdump',     # binary disassembler cross-check
    'riscv-spec',  # RISC-V official ISA specification
    'arm-arm',     # ARM Architecture Reference Manual
    'intel-sdm',   # Intel Software Developer's Manual
    'manual',      # hand-derived (must be reviewed)
}

def typecheck_isa(regclasses: list[RegClass], mcinsns: list[McInsn]) -> list[IsaDiag]:
    """Validate internal consistency of parsed .isa definitions."""
    diags = []

    # Build register name set from all regclasses
    all_regs = set()
    for rc in regclasses:
        for r in rc.regs:
            all_regs.add(r)

    # Build regclass name → RegClass map
    rc_map = {rc.name: rc for rc in regclasses}

    seen_names = set()
    for insn in mcinsns:
        # Duplicate name check
        if insn.name in seen_names:
            diags.append(IsaDiag('error', insn.name, 'duplicate mcinsn name'))
        seen_names.add(insn.name)

        # min/max bytes
        if insn.min_bytes <= 0:
            diags.append(IsaDiag('error', insn.name, ':min-bytes must be > 0'))
        if insn.max_bytes < insn.min_bytes:
            diags.append(IsaDiag('error', insn.name, ':max-bytes < :min-bytes'))

        # Operand extraction
        operands = extract_operands(insn)
        op_names = {op.name for op in operands}

        # Check encoding references valid operands
        if insn.encoding:
            enc_vars = _collect_variables(insn.encoding)
            for var in enc_vars:
                if var not in op_names:
                    diags.append(IsaDiag('error', insn.name,
                                         f'encoding references undefined operand {var}'))

        # :golden-bytes is the primary encoding contract — required for every mcinsn
        if not insn.golden_bytes:
            diags.append(IsaDiag('error', insn.name,
                                 ':golden-bytes is required (at least one entry)'))

        # :golden-asm is the disassembly contract — at least one canonical asm
        # row is required so future generated disasm / llvm-mc round-trip has a
        # grounded expected string. Row count may be smaller than :golden-bytes
        # because multiple encoding variants commonly share one canonical asm.
        if not insn.golden_asm:
            diags.append(IsaDiag('error', insn.name,
                                 ':golden-asm is required (at least one canonical row)'))
        elif len(insn.golden_asm) > len(insn.golden_bytes):
            diags.append(IsaDiag(
                'error', insn.name,
                f':golden-asm row count ({len(insn.golden_asm)}) must not '
                f'exceed :golden-bytes row count ({len(insn.golden_bytes)})'))

        # :external-reference points at the third-party source that produced the
        # golden values. Must be a documented reference so reviewers can cross-check.
        if not insn.external_ref:
            diags.append(IsaDiag('error', insn.name,
                                 ':external-reference is required'))
        elif insn.external_ref not in VALID_EXTERNAL_REFERENCES:
            diags.append(IsaDiag(
                'error', insn.name,
                f':external-reference {insn.external_ref!r} is not in the '
                f'documented set {sorted(VALID_EXTERNAL_REFERENCES)}'))

        # Golden bytes: validate hex string format
        for regs, hex_str in insn.golden_bytes:
            hex_bytes = hex_str.split()
            for hb in hex_bytes:
                if len(hb) != 2 or not all(c in '0123456789abcdefABCDEF' for c in hb):
                    diags.append(IsaDiag('error', insn.name,
                                         f'invalid hex byte "{hb}" in :golden-bytes'))
            # Check byte count vs min/max
            n_bytes = len(hex_bytes)
            if n_bytes < insn.min_bytes or n_bytes > insn.max_bytes:
                diags.append(IsaDiag('warn', insn.name,
                                     f'golden-bytes length {n_bytes} outside '
                                     f'[{insn.min_bytes}, {insn.max_bytes}]'))

        # Golden bytes: register names should be in regclass (if regs provided)
        for regs, _ in insn.golden_bytes:
            for r in regs:
                # Skip numeric immediate values
                try:
                    int(r, 0)
                    continue
                except ValueError:
                    pass
                if r.startswith('-'):
                    try:
                        int(r, 0)
                        continue
                    except ValueError:
                        pass
                if all_regs and r not in all_regs:
                    diags.append(IsaDiag('warn', insn.name,
                                         f'golden-bytes register "{r}" not in any regclass'))

    return diags

def _collect_variables(node: SExpr) -> set[str]:
    """Recursively collect all $variable names from an S-expression tree."""
    result = set()
    if isinstance(node, SAtom):
        if node.is_variable:
            result.add(node.value)
    elif isinstance(node, SList):
        for child in node.children:
            result.update(_collect_variables(child))
    return result

