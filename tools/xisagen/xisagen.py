def _test_isa_parser():
    print("  test_isa_parser...", end='', file=sys.stderr)
    text = '''
    (define-regclass x64.gpr64
      :regs (rax rcx rdx rbx)
      :encoding-bits 4)
    (define-mcinsn x64.add.rr
      :operands       (($dst reg:gpr64) ($src reg:gpr64))
      :constraints    ((same $dst $src))
      :encoding       (rex.w 0x01 (modrm 0b11 $src $dst))
      :flags          ()
      :min-bytes      3
      :max-bytes      3
      :golden-bytes   (((rax rbx) "48 01 d8"))
      :golden-asm     (((rax rbx) "add rax, rbx"))
      :external-reference llvm-mc)
    '''
    tokens = tokenize_sexpr(text, 'test.isa')
    forms = parse_sexpr(tokens, 'test.isa')
    assert len(forms) == 2

    # Extract
    rc = extract_regclass(forms[0])
    assert rc.name == 'x64.gpr64'
    assert len(rc.regs) == 4
    assert rc.encoding_bits == 4

    insn = extract_mcinsn(forms[1])
    assert insn.name == 'x64.add.rr'
    assert insn.min_bytes == 3
    assert insn.max_bytes == 3
    assert len(insn.golden_bytes) == 1
    assert insn.golden_bytes[0] == (['rax', 'rbx'], '48 01 d8')
    assert insn.golden_asm[0] == (['rax', 'rbx'], 'add rax, rbx')
    assert insn.external_ref == 'llvm-mc'

    print(" PASS", file=sys.stderr)


