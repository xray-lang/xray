# ============================================================
# Disassembler generation (arm64 / riscv64 fixed-32-bit only)
# ============================================================
#
# For fixed-size architectures we already extract a `(fixed_mask,
# fixed_value)` pair per mcinsn for `disasm-check`. The same table can
# drive an actual decoder: linear scan, sorted by mask popcount
# descending so the most-specific match wins. This generator emits a
# `xm_<arch>_disasm_gen.{c,h}` pair exporting:
#   - `Xm<Arch>InsnId` enum, one entry per mcinsn (id == declaration order)
#   - `xm_<short>_insn_name(int id)`        — id → mcinsn-name string
#   - `xm_<short>_disasm(uint32_t insn)`    — bytes → id (or _UNKNOWN)
# Used today as a runtime lookup for patch verifiers / deopt logs and as
# a foundation for later external-diff work.

_DISASM_ARCH_INFO = {
    'arm64':   {'short': 'a64',  'enum_prefix': 'A64',  'pattern_fn_name': '_arm64_fixed_pattern'},
    'riscv64': {'short': 'rv64', 'enum_prefix': 'RV64', 'pattern_fn_name': '_riscv64_fixed_pattern'},
}


def _disasm_stem(arch: str, mcinsn_name: str) -> str:
    """Convert e.g. 'arm64.fcvt_d_s' → 'FCVT_D_S' (enum stem)."""
    bare = mcinsn_name.removeprefix(f'{arch}.')
    return bare.upper().replace('.', '_').replace('-', '_')


def generate_disasm_header(arch: str, mcinsns: list) -> str:
    info = _DISASM_ARCH_INFO[arch]
    short = info['short']
    eprefix = info['enum_prefix']
    type_name = f'Xm{eprefix.title()}InsnId'  # XmA64InsnId / XmRv64InsnId

    lines = []
    lines.append('/* AUTO-GENERATED by xisagen — DO NOT EDIT */')
    lines.append(f'/* Disassembler for {arch} (fixed-bit pattern matching) */')
    lines.append('')
    lines.append('#pragma once')
    lines.append('')
    lines.append('#include <stdint.h>')
    lines.append('')
    lines.append('typedef enum {')
    lines.append(f'    XM_{eprefix}_INSN_UNKNOWN = -1,')
    for i, insn in enumerate(mcinsns):
        stem = _disasm_stem(arch, insn.name)
        lines.append(f'    XM_{eprefix}_INSN_{stem} = {i},')
    lines.append(f'    XM_{eprefix}_INSN__COUNT = {len(mcinsns)}')
    lines.append(f'}} {type_name};')
    lines.append('')
    lines.append(f'/* Returns the mcinsn name string (e.g. "{arch}.add.rrr") for the given')
    lines.append(' * id, or "(unknown)" if id is out of range. */')
    lines.append(f'const char *xm_{short}_insn_name(int id);')
    lines.append('')
    lines.append(f'/* Decode a 32-bit instruction word and return the matching')
    lines.append(f' * Xm{eprefix.title()}InsnId, or XM_{eprefix}_INSN_UNKNOWN if no mcinsn pattern')
    lines.append(' * matches. The most-specific (largest fixed_mask popcount) match wins. */')
    lines.append(f'int xm_{short}_disasm(uint32_t insn);')
    lines.append('')
    return '\n'.join(lines)


def generate_disasm_impl(arch: str, mcinsns: list, pattern_fn) -> str:
    info = _DISASM_ARCH_INFO[arch]
    short = info['short']
    eprefix = info['enum_prefix']

    # Build (popcount-desc-sorted) entries for the decoder, keeping only
    # mcinsns with a non-zero fixed_mask (others can never match).
    entries = []
    for insn in mcinsns:
        mask, value = pattern_fn(insn)
        if mask == 0:
            continue
        entries.append((insn.name, mask, value))
    entries.sort(key=lambda e: (-bin(e[1]).count('1'), e[0]))

    lines = []
    lines.append('/* AUTO-GENERATED by xisagen — DO NOT EDIT */')
    lines.append(f'#include "xm_{arch}_disasm_gen.h"')
    lines.append('')
    lines.append('#include <stddef.h>')
    lines.append('')
    lines.append('typedef struct {')
    lines.append('    uint32_t    mask;')
    lines.append('    uint32_t    value;')
    lines.append('    int         id;')
    lines.append('    const char *name;')
    lines.append(f'}} Xm{eprefix.title()}DisasmEntry;')
    lines.append('')
    lines.append('/* Sorted by fixed-mask popcount descending (most-specific first). */')
    lines.append(f'static const Xm{eprefix.title()}DisasmEntry kEntries[] = {{')
    for name, mask, value in entries:
        stem = _disasm_stem(arch, name)
        lines.append(f'    {{ 0x{mask:08x}u, 0x{value:08x}u, XM_{eprefix}_INSN_{stem}, "{name}" }},')
    lines.append(f'}};')
    lines.append('')
    lines.append('static const char *kNamesById[] = {')
    for insn in mcinsns:
        lines.append(f'    "{insn.name}",')
    lines.append('};')
    lines.append('')
    lines.append(f'const char *xm_{short}_insn_name(int id) {{')
    lines.append(f'    if (id < 0 || id >= XM_{eprefix}_INSN__COUNT) return "(unknown)";')
    lines.append(f'    return kNamesById[id];')
    lines.append('}')
    lines.append('')
    lines.append(f'int xm_{short}_disasm(uint32_t insn) {{')
    lines.append('    size_t n = sizeof(kEntries) / sizeof(kEntries[0]);')
    lines.append('    for (size_t i = 0; i < n; ++i) {')
    lines.append('        if ((insn & kEntries[i].mask) == kEntries[i].value) {')
    lines.append('            return kEntries[i].id;')
    lines.append('        }')
    lines.append('    }')
    lines.append(f'    return XM_{eprefix}_INSN_UNKNOWN;')
    lines.append('}')
    lines.append('')
    return '\n'.join(lines)


def generate_disasm_test(arch: str, mcinsns: list, pattern_fn) -> str:
    """Generate a runtime C test that decodes every 4-byte :golden-bytes row
    via the generated `xm_<short>_disasm()` and asserts the returned id matches
    the declared mcinsn (or a documented assembler-pseudo overlap winner).

    Cross-platform: the disasm is pure table lookup, no CPU-specific ops.
    """
    info = _DISASM_ARCH_INFO[arch]
    short = info['short']
    eprefix = info['enum_prefix']

    # For each row, compute the expected id. For known assembler-pseudo
    # overlaps where the declared mcinsn is *less* specific than another
    # matching mcinsn, the disasm will return the more-specific one — so
    # the test accepts the most-specific match as the expected answer.
    #
    # Sort key MUST match `generate_disasm_impl`'s entry sort exactly, so
    # equal-popcount tiebreaks resolve identically here and at runtime.
    patterns = {insn.name: pattern_fn(insn) for insn in mcinsns}
    sorted_names = sorted(
        patterns,
        key=lambda n: (-bin(patterns[n][0]).count('1'), n))

    def expected_id_for_bytes(declared_name: str, insn_bits: int) -> str:
        """Return the C enum stem for the mcinsn the decoder will pick."""
        # Linear scan in popcount-desc order — same as runtime decoder
        for cand in sorted_names:
            mask, value = patterns[cand]
            if mask == 0:
                continue
            if (insn_bits & mask) == value:
                return _disasm_stem(arch, cand)
        return ''  # decoder would return UNKNOWN — caller skips

    rows = []  # [(desc, insn_bits, expected_stem)]
    for insn in mcinsns:
        mask, value = patterns[insn.name]
        if mask == 0:
            continue
        for regs, hex_str in insn.golden_bytes:
            insn_bits = _golden_bytes_to_uint32(hex_str)
            if insn_bits is None:
                continue
            if (insn_bits & mask) != value:
                # disasm-check would already report this; skip the row here
                # so the runtime test focuses on the *successful* decode path.
                continue
            stem = expected_id_for_bytes(insn.name, insn_bits)
            if not stem:
                continue
            desc = f'{insn.name} {regs!r}'.replace('"', "'")
            rows.append((desc, insn_bits, stem))

    lines = []
    lines.append('/* AUTO-GENERATED by xisagen — DO NOT EDIT */')
    lines.append(f'/* Disassembler round-trip test for {arch} (cross-platform table lookup). */')
    lines.append('')
    lines.append('#include <stdio.h>')
    lines.append('#include <stdint.h>')
    lines.append(f'#include "xm_{arch}_disasm_gen.h"')
    lines.append('')
    lines.append('static int g_pass = 0;')
    lines.append('static int g_fail = 0;')
    lines.append('')
    lines.append('static void check_disasm(const char *desc, uint32_t insn, int expected) {')
    lines.append(f'    int got = xm_{short}_disasm(insn);')
    lines.append('    if (got != expected) {')
    lines.append('        fprintf(stderr, "FAIL: %s (0x%08x): expected %d (%s), got %d (%s)\\n",')
    lines.append(f'                desc, insn, expected, xm_{short}_insn_name(expected),')
    lines.append(f'                got, xm_{short}_insn_name(got));')
    lines.append('        g_fail++;')
    lines.append('    } else {')
    lines.append('        g_pass++;')
    lines.append('    }')
    lines.append('}')
    lines.append('')
    lines.append('int main(void) {')
    for desc, bits, stem in rows:
        lines.append(f'    check_disasm("{desc}", 0x{bits:08x}u, XM_{eprefix}_INSN_{stem});')
    lines.append('')
    lines.append('    if (g_fail > 0) {')
    lines.append('        fprintf(stderr, "%d disasm tests failed, %d passed\\n", g_fail, g_pass);')
    lines.append('        return 1;')
    lines.append('    }')
    lines.append('    fprintf(stderr, "All %d disasm tests passed\\n", g_pass);')
    lines.append('    return 0;')
    lines.append('}')
    lines.append('')
    return '\n'.join(lines)


