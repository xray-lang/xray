def cmd_ops(args: list[str]):
    if len(args) != 2:
        die("usage: xisagen.py ops <ops.def> <output.h>")
    ops = parse_ops_def(read_file(args[0]))
    if not ops:
        die(f"no ops parsed from {args[0]}")
    content = generate_ops_header(ops)
    write_file(args[1], content)
    print(f"xisagen: parsed {len(ops)} ops from {args[0]}", file=sys.stderr)
    print(f"xisagen: generated {args[1]}", file=sys.stderr)

def cmd_helpers(args: list[str]):
    if len(args) != 2:
        die("usage: xisagen.py helpers <helpers.def> <output.h>")
    helpers = parse_helpers_def(read_file(args[0]))
    if not helpers:
        die(f"no helpers parsed from {args[0]}")
    content = generate_helpers_header(helpers)
    write_file(args[1], content)
    print(f"xisagen: parsed {len(helpers)} helpers from {args[0]}", file=sys.stderr)
    print(f"xisagen: generated {args[1]}", file=sys.stderr)

def cmd_isa(args: list[str]):
    if len(args) < 1:
        die("usage: xisagen.py isa <isa.isa> [output_dir]")
    path = args[0]
    regclasses, mcinsns = load_isa(path)
    print(f"xisagen: parsed {path}: {len(regclasses)} regclasses, {len(mcinsns)} mcinsns",
          file=sys.stderr)

    # Validate golden bytes
    total_golden = sum(len(m.golden_bytes) for m in mcinsns)
    total_golden_asm = sum(len(m.golden_asm) for m in mcinsns)
    print(f"xisagen: {total_golden} golden-bytes, {total_golden_asm} golden-asm entries",
          file=sys.stderr)

    for insn in mcinsns:
        if insn.min_bytes <= 0:
            die(f"{path}: {insn.name}: missing :min-bytes")
        if insn.max_bytes < insn.min_bytes:
            die(f"{path}: {insn.name}: :max-bytes < :min-bytes")
        if not insn.golden_bytes:
            die(f"{path}: {insn.name}: no :golden-bytes")

def cmd_test(args: list[str]):
    """Run self-tests."""
    print("xisagen self-test:", file=sys.stderr)
    _test_sexpr_parser()
    _test_ops_parser()
    _test_helpers_parser()
    _test_isa_parser()
    print("All xisagen self-tests passed.", file=sys.stderr)

def _test_sexpr_parser():
    print("  test_sexpr_parser...", end='', file=sys.stderr)
    tokens = tokenize_sexpr('(add 1 2)')
    forms = parse_sexpr(tokens)
    assert len(forms) == 1
    assert isinstance(forms[0], SList)
    assert len(forms[0].children) == 3
    assert isinstance(forms[0].children[0], SAtom) and forms[0].children[0].value == 'add'
    assert forms[0].children[1].int_value == 1
    assert forms[0].children[2].int_value == 2

    # Keywords and variables
    tokens = tokenize_sexpr('(:key $var "str" 0xFF 0b1101)')
    forms = parse_sexpr(tokens)
    lst = forms[0]
    assert lst.children[0].is_keyword
    assert lst.children[1].is_variable
    assert lst.children[2].is_string
    assert lst.children[3].int_value == 255
    assert lst.children[4].int_value == 13

    # Comments
    tokens = tokenize_sexpr('foo ; comment\nbar')
    forms = parse_sexpr(tokens)
    assert len(forms) == 2

    # Nested
    tokens = tokenize_sexpr('(a (b c) d)')
    forms = parse_sexpr(tokens)
    assert len(forms[0].children) == 3
    assert isinstance(forms[0].children[1], SList)

    # Keyword lookup
    tokens = tokenize_sexpr('(foo :min-bytes 3 :name "test")')
    forms = parse_sexpr(tokens)
    lst = forms[0]
    assert lst.get_kw_int(':min-bytes') == 3
    assert lst.get_kw_str(':name') == 'test'

    print(" PASS", file=sys.stderr)

def _test_ops_parser():
    print("  test_ops_parser...", end='', file=sys.stderr)
