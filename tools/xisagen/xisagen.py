@dataclass
class McInsn:
    """Parsed machine instruction definition."""
    name: str
    operands: Optional[SList] = None
    constraints: Optional[SList] = None
    encoding: Optional[SList] = None
    flags: list = field(default_factory=list)
    min_bytes: int = 0
    max_bytes: int = 0
    golden_bytes: list = field(default_factory=list)  # [(regs, hex_str), ...]
    golden_asm: list = field(default_factory=list)
    decode_priority: str = 'normal'
    external_ref: str = ''
    helper: str = ''
    raw: Optional[SList] = None  # original S-expression

@dataclass
class RegClass:
    """Register class definition."""
    name: str
    regs: list          # register names
    encoding_bits: int

def extract_mcinsn(form: SList) -> McInsn:
    """Extract McInsn from a (define-mcinsn ...) form."""
    children = form.children
    assert len(children) >= 2
    name = children[1].value if isinstance(children[1], SAtom) else '???'

    insn = McInsn(name=name, raw=form)
    insn.operands = form.get_kw_list(':operands')
    insn.constraints = form.get_kw_list(':constraints')
    insn.encoding = form.get_kw_list(':encoding')
    insn.min_bytes = form.get_kw_int(':min-bytes')
    insn.max_bytes = form.get_kw_int(':max-bytes')
    insn.decode_priority = form.get_kw_str(':decode-priority', 'normal')
    insn.external_ref = form.get_kw_str(':external-reference', '')
    insn.helper = form.get_kw_str(':helper', '')

    # Flags
    flags_list = form.get_kw_list(':flags')
    if flags_list:
        insn.flags = [c.value for c in flags_list.children if isinstance(c, SAtom)]

    # Golden bytes: (((regs...) "hex") ...)
    gb = form.get_kw_list(':golden-bytes')
    if gb:
        for entry in gb.children:
            if isinstance(entry, SList) and len(entry.children) >= 2:
                regs_node = entry.children[0]
                hex_node = entry.children[1]
                regs = []
                if isinstance(regs_node, SList):
                    regs = [c.value if isinstance(c, SAtom) else str(c)
                            for c in regs_node.children]
                hex_str = hex_node.str_value if isinstance(hex_node, SAtom) else ''
                insn.golden_bytes.append((regs, hex_str))

    # Golden asm
    ga = form.get_kw_list(':golden-asm')
    if ga:
        for entry in ga.children:
            if isinstance(entry, SList) and len(entry.children) >= 2:
                regs_node = entry.children[0]
                asm_node = entry.children[1]
                regs = []
                if isinstance(regs_node, SList):
                    regs = [c.value if isinstance(c, SAtom) else str(c)
                            for c in regs_node.children]
                asm_str = asm_node.str_value if isinstance(asm_node, SAtom) else ''
                insn.golden_asm.append((regs, asm_str))

    return insn

def extract_regclass(form: SList) -> RegClass:
    """Extract RegClass from a (define-regclass ...) form."""
    name = form.children[1].value if len(form.children) >= 2 and isinstance(form.children[1], SAtom) else '???'
    regs = []
    regs_list = form.get_kw_list(':regs')
    if regs_list:
        regs = [c.value for c in regs_list.children if isinstance(c, SAtom)]
    bits = form.get_kw_int(':encoding-bits', 4)
    return RegClass(name=name, regs=regs, encoding_bits=bits)

def load_isa_text(text: str, name: str = '<text>') -> tuple[list[RegClass], list[McInsn]]:
    """Parse .isa from a string, returning regclasses and mcinsns."""
    tokens = tokenize_sexpr(text, name)
    forms = parse_sexpr(tokens, name)
    regclasses = []
    mcinsns = []
    for form in forms:
        if not isinstance(form, SList) or not form.children:
            continue
        head = form.head
        if isinstance(head, SAtom):
            if head.value == 'define-mcinsn':
                mcinsns.append(extract_mcinsn(form))
            elif head.value == 'define-regclass':
                regclasses.append(extract_regclass(form))
    return regclasses, mcinsns

def load_isa(path: str) -> tuple[list[RegClass], list[McInsn]]:
    """Load and parse a .isa file, returning regclasses and mcinsns."""
    forms = parse_isa_file(path)
    regclasses = []
    mcinsns = []
    for form in forms:
        if not isinstance(form, SList) or not form.children:
            continue
        head = form.head
        if isinstance(head, SAtom):
            if head.value == 'define-mcinsn':
                mcinsns.append(extract_mcinsn(form))
            elif head.value == 'define-regclass':
                regclasses.append(extract_regclass(form))
    return regclasses, mcinsns

