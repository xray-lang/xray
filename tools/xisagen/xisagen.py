#!/usr/bin/env python3
"""
xisagen — XISA code generator (Python rewrite)

Reads declarative .def and .isa files, generates C headers for the JIT:
  - ops:     xisa/xm/ops.def     → xm_ops_gen.h
  - helpers: xisa/xm/helpers.def → xm_helpers_gen.h
  - isa:     xisa/arch/<arch>/isa.isa → emit helpers, mcattr, disasm, golden

Usage:
  python3 xisagen.py ops     <ops.def>     <output.h>
  python3 xisagen.py helpers <helpers.def> <output.h>
  python3 xisagen.py isa     <isa.isa>     <output_dir>
"""

import sys
import re
import os
from dataclasses import dataclass, field
from typing import Optional

# ============================================================
# Common utilities
# ============================================================

def die(msg: str):
    print(f"xisagen: error: {msg}", file=sys.stderr)
    sys.exit(1)

def read_file(path: str) -> str:
    try:
        with open(path, 'r') as f:
            return f.read()
    except OSError as e:
        die(f"cannot read {path}: {e}")

def write_file(path: str, content: str):
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    with open(path, 'w') as f:
        f.write(content)

# ============================================================
# L1: ops.def parser + generator
# ============================================================

@dataclass
class OpDef:
    name: str       # e.g. "ADD"
    cls: str        # e.g. "ARITH"
    nargs: int
    rep: str        # "I64", "F64", "PTR", "TAGGED", "VOID"
    flags: list     # ["COMMUTATIVE", "SIDE_EFFECT", ...]

def parse_ops_def(text: str) -> list[OpDef]:
    ops = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith('#') or line.startswith('//'):
            continue
        # XM_DEF(NAME, CLASS, NARGS, REP, FLAGS) or XM_OP(...)
        m = re.match(r'XM_(?:DEF|OP)\(\s*(\w+)\s*,\s*(\w+)\s*,\s*(\d+)\s*,\s*(\w+)\s*,\s*([^)]*)\)', line)
        if not m:
            continue
        name, cls, nargs, rep, flags_str = m.groups()
        flags = [f.strip() for f in flags_str.split('|') if f.strip() and f.strip() != 'NONE']
        ops.append(OpDef(name=name, cls=cls, nargs=int(nargs), rep=rep, flags=flags))
    return ops

def generate_ops_header(ops: list[OpDef]) -> str:
    """Generate xm_ops_gen.h matching the format expected by xm_ops.h consumers."""
    lines = []
    lines.append('/* AUTO-GENERATED by xisagen — DO NOT EDIT */')
    lines.append('/* Source: xisa/xm/ops.def */')
    lines.append('')
    lines.append('#ifndef XM_OPS_GEN_H')
    lines.append('#define XM_OPS_GEN_H')
    lines.append('')
    lines.append('#include <stdint.h>')
    lines.append('')

    # Effect flags (stable bit assignments matching existing code)
    EF_BITS = {'GC': 0, 'THROW': 1, 'SUSPEND': 2, 'DEOPT': 3, 'WRITE': 4, 'READ': 5}
    lines.append('/* ========== Effect Flags ========== */')
    lines.append('')
    lines.append('#define XM_EF_NONE 0')
    for name, bit in EF_BITS.items():
        lines.append(f'#define XM_EF_{name} (1u << {bit})')
    lines.append('')

    # Op classes — preserve insertion order from ops.def
    seen_classes = []
    for op in ops:
        if op.cls not in seen_classes:
            seen_classes.append(op.cls)
    lines.append('/* ========== Opcode Classes ========== */')
    lines.append('')
    lines.append('typedef enum {')
    for i, cls in enumerate(seen_classes):
        lines.append(f'    XM_CLASS_{cls} = {i},')
    lines.append('    XM_CLASS__COUNT')
    lines.append('} XmOpClass;')
    lines.append('')

    # Op enum
    lines.append('/* ========== Xm Opcodes ========== */')
    lines.append('')
    lines.append('typedef enum {')
    for i, op in enumerate(ops):
        lines.append(f'    XM_{op.name} = {i},')
    lines.append('')
    lines.append('    XM_OP_COUNT, /* sentinel */')
    lines.append('')
    lines.append('    /* Machine opcodes (filled by isel, share the same XmIns layout) */')
    lines.append('    XM_MACH_BASE = 256,')
    lines.append('} XmOp;')
    lines.append('')

    # Op metadata struct
    lines.append('/* ========== Op Metadata ========== */')
    lines.append('')
    lines.append('typedef struct {')
    lines.append('    const char *name;   /* string name (e.g. "ADD") */')
    lines.append('    uint8_t op_class;   /* XmOpClass */')
    lines.append('    uint8_t nargs;      /* number of XmRef arguments */')
    lines.append('    uint8_t result_rep; /* XrRep of result */')
    lines.append('    uint8_t effects;    /* XM_EF_* bitfield */')
    lines.append('} XmOpInfo;')
    lines.append('')

    # Op info table
    lines.append('/* ========== Op Info Table (indexed by XmOp) ========== */')
    lines.append('')
    lines.append('#ifdef XM_OPS_IMPL')
    lines.append('static const XmOpInfo xm_op_info[XM_OP_COUNT] = {')
    for op in ops:
        flags_expr = ' | '.join(f'XM_EF_{f}' for f in op.flags) if op.flags else '0'
        lines.append(f'    [XM_{op.name}] = {{"{op.name}", '
                     f'XM_CLASS_{op.cls}, {op.nargs}, XR_REP_{op.rep}, {flags_expr}}},')
    lines.append('};')
    lines.append('#else')
    lines.append('extern const XmOpInfo xm_op_info[XM_OP_COUNT];')
    lines.append('#endif')
    lines.append('')

    lines.append('#endif  // XM_OPS_GEN_H')
    lines.append('')
    return '\n'.join(lines)

