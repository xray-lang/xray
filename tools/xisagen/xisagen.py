def _arm64_fixed_pattern(insn) -> tuple[int, int]:
    """Compute (fixed_mask, fixed_value) for an arm64 mcinsn encoding.

    Fixed bits are bits that are always the same regardless of operand values.
    Variable bits (filled by $vars via `field` / `field-scaled` / `field-xor`)
    are excluded. Numeric constants inside `field` (e.g. fixed `rs2=0` in some
    encodings) contribute to the fixed pattern.

    `field-xor N W $var K` is treated as variable since the value depends on
    the runtime operand even though it's combined with a fixed constant K.
    """
    if not insn.encoding:
        return (0, 0)
    enc = insn.encoding.children
    base = 0
    variable_mask = 0
    for elem in enc:
        if isinstance(elem, SAtom) and elem.is_number:
            base |= elem.int_value & 0xFFFFFFFF
        elif isinstance(elem, SList) and elem.children:
            head_atom = elem.children[0]
            head_val = head_atom.value if isinstance(head_atom, SAtom) else ''
            if head_val in ('field', 'field-scaled', 'field-xor'):
                ch = elem.children
                bit_off = ch[1].int_value if len(ch) > 1 and isinstance(ch[1], SAtom) and ch[1].is_number else 0
                width = ch[2].int_value if len(ch) > 2 and isinstance(ch[2], SAtom) and ch[2].is_number else 0
                operand = ch[3] if len(ch) > 3 else None
                width_mask = ((1 << width) - 1) << bit_off
                if operand and isinstance(operand, SAtom):
                    if operand.is_variable:
                        variable_mask |= width_mask
                    elif operand.is_number:
                        base |= ((operand.int_value & ((1 << width) - 1)) << bit_off) & 0xFFFFFFFF
                else:
                    variable_mask |= width_mask
    fixed_mask = (~variable_mask) & 0xFFFFFFFF
    fixed_value = base & fixed_mask
    return (fixed_mask, fixed_value)


def _riscv64_fixed_pattern(insn) -> tuple[int, int]:
    """Compute (fixed_mask, fixed_value) for a riscv64 mcinsn encoding.

    Recognises the six standard formats (r-type / i-type / s-type / b-type
    / u-type / j-type) and raw 32-bit constants. Variable register/imm
    positions become non-fixed; numeric constants in those positions remain
    fixed.
    """
    if not insn.encoding or not insn.encoding.children:
        return (0, 0)
    enc = insn.encoding.children
    head = enc[0]

    if isinstance(head, SAtom) and head.is_number:
        return (0xFFFFFFFF, head.int_value & 0xFFFFFFFF)

    fmt = head.value if isinstance(head, SAtom) else ''

    def is_var(idx: int) -> bool:
        return idx < len(enc) and isinstance(enc[idx], SAtom) and enc[idx].is_variable

    def const_val(idx: int):
        if idx < len(enc) and isinstance(enc[idx], SAtom) and enc[idx].is_number:
            return enc[idx].int_value
        return None

    base = 0
    variable_mask = 0

    def fix_field(value, width: int, bit_off: int):
        nonlocal base
        if value is not None:
            base |= ((value & ((1 << width) - 1)) << bit_off) & 0xFFFFFFFF

    def var_field(width: int, bit_off: int):
        nonlocal variable_mask
        variable_mask |= ((1 << width) - 1) << bit_off

    if fmt == 'r-type':
        fix_field(const_val(1), 7, 0)
        fix_field(const_val(2), 3, 12)
        fix_field(const_val(3), 7, 25)
        for field_idx, width, bit_off in ((4, 5, 7), (5, 5, 15), (6, 5, 20)):
            if is_var(field_idx):
                var_field(width, bit_off)
            else:
                fix_field(const_val(field_idx), width, bit_off)
    elif fmt == 'i-type':
        fix_field(const_val(1), 7, 0)
        fix_field(const_val(2), 3, 12)
        for field_idx, width, bit_off in ((3, 5, 7), (4, 5, 15)):
            if is_var(field_idx):
                var_field(width, bit_off)
            else:
                fix_field(const_val(field_idx), width, bit_off)
        if is_var(5):
            var_field(12, 20)
        else:
            fix_field(const_val(5), 12, 20)
    elif fmt == 's-type':
        fix_field(const_val(1), 7, 0)
        fix_field(const_val(2), 3, 12)
        for field_idx, width, bit_off in ((3, 5, 15), (4, 5, 20)):
            if is_var(field_idx):
                var_field(width, bit_off)
            else:
                fix_field(const_val(field_idx), width, bit_off)
        if is_var(5):
            var_field(5, 7)
            var_field(7, 25)
        else:
            iv = const_val(5)
            if iv is not None:
                base |= ((iv & 0x1f) << 7) & 0xFFFFFFFF
                base |= (((iv >> 5) & 0x7f) << 25) & 0xFFFFFFFF
    elif fmt == 'b-type':
        fix_field(const_val(1), 7, 0)
        fix_field(const_val(2), 3, 12)
        for field_idx, width, bit_off in ((3, 5, 15), (4, 5, 20)):
            if is_var(field_idx):
                var_field(width, bit_off)
            else:
                fix_field(const_val(field_idx), width, bit_off)
        if is_var(5):
            variable_mask |= (1 << 7) | (0xf << 8) | (0x3f << 25) | (1 << 31)
        else:
            iv = const_val(5)
            if iv is not None:
                base |= (((iv >> 11) & 1) << 7) & 0xFFFFFFFF
                base |= (((iv >> 1) & 0xf) << 8) & 0xFFFFFFFF
                base |= (((iv >> 5) & 0x3f) << 25) & 0xFFFFFFFF
                base |= (((iv >> 12) & 1) << 31) & 0xFFFFFFFF
    elif fmt == 'u-type':
        fix_field(const_val(1), 7, 0)
        if is_var(2):
            var_field(5, 7)
        else:
            fix_field(const_val(2), 5, 7)
        if is_var(3):
            var_field(20, 12)
        else:
            fix_field(const_val(3), 20, 12)
    elif fmt == 'j-type':
        fix_field(const_val(1), 7, 0)
        if is_var(2):
            var_field(5, 7)
        else:
            fix_field(const_val(2), 5, 7)
        if is_var(3):
            variable_mask |= (0xff << 12) | (1 << 20) | (0x3ff << 21) | (1 << 31)
        else:
            iv = const_val(3)
            if iv is not None:
                base |= (((iv >> 12) & 0xff) << 12) & 0xFFFFFFFF
                base |= (((iv >> 11) & 1) << 20) & 0xFFFFFFFF
                base |= (((iv >> 1) & 0x3ff) << 21) & 0xFFFFFFFF
                base |= (((iv >> 20) & 1) << 31) & 0xFFFFFFFF
    else:
        return (0, 0)

    fixed_mask = (~variable_mask) & 0xFFFFFFFF
    fixed_value = base & fixed_mask
    return (fixed_mask, fixed_value)


# Known-by-design encoding overlaps. Each entry is a *sorted* (a, b) pair of
# mcinsn names where one is a strict special case of the other in the actual
# ISA, so the fixed-bit-only check can't distinguish them. Disambiguation
# happens at the operand-value level (e.g. arm64.neg.rr = arm64.sub.rrr with
# rn=XZR; riscv64.srai = riscv64.srli with imm[11:5]=0b0100000).
_EXPECTED_ENCODING_OVERLAPS: set = {
    # arm64 assembler-pseudo overlaps
    ('arm64.add.lsl',   'arm64.add.rrr'),   # add (lsl shift=0) == add reg,reg
    ('arm64.neg.rr',    'arm64.sub.rrr'),   # neg = sub with rn=XZR
    ('arm64.mov.rr',    'arm64.orr.rrr'),   # mov (reg) = orr with rn=XZR
    ('arm64.cmp.rr',    'arm64.subs.rrr'),  # cmp = subs with rd=XZR
    # riscv64 pseudo overlaps
    ('riscv64.addi',    'riscv64.nop'),      # nop = addi x0, x0, 0
    # riscv64 shifts where SRAI/SRLI share opcode+funct3, differ via imm[11:5].
    # The .isa exposes the shamt+funct7 as a single imm12, so the fixed-bit
    # check sees them as identical at the opcode level. Real disasm uses
    # imm[10] to pick between them.
    ('riscv64.srai',    'riscv64.srli'),
    ('riscv64.sraiw',   'riscv64.srliw'),
}


def _check_fixed_uniqueness(mcinsns: list, pattern_fn) -> list:
    """Find decode-ambiguous mcinsn pairs.

    Two mcinsns are ambiguous when the bits both declare as fixed (the
    intersection of their fixed masks) carry identical fixed values. On any
    input bytes that match the shared fixed bits, a decoder cannot tell
    them apart from the fixed-pattern alone.

    Pairs in `_EXPECTED_ENCODING_OVERLAPS` are filtered out as known
    assembler-pseudo or operand-level overlaps; any new ambiguity not in
    that allowlist must be either fixed in the .isa or added there.

    Returns a list of (name_a, name_b, common_mask, common_value) tuples.
    """
    patterns = []
    for insn in mcinsns:
        fm, fv = pattern_fn(insn)
        patterns.append((insn.name, fm, fv))

    ambig = []
    for i in range(len(patterns)):
        name_a, mask_a, val_a = patterns[i]
        if mask_a == 0:
            continue
        for j in range(i + 1, len(patterns)):
            name_b, mask_b, val_b = patterns[j]
            if mask_b == 0:
                continue
            common = mask_a & mask_b
            if common == 0:
                continue
            if (val_a & common) == (val_b & common):
                key = tuple(sorted((name_a, name_b)))
                if key in _EXPECTED_ENCODING_OVERLAPS:
                    continue
                ambig.append((name_a, name_b, common, val_a & common))
    return ambig


def _golden_bytes_to_uint32(hex_str: str):
    """Parse a 4-byte little-endian golden-bytes hex string into a uint32.

    Returns None if the row isn't a fixed 4-byte instruction (e.g. variable-
    length x64 entries).
    """
    parts = hex_str.split()
    if len(parts) != 4:
        return None
    try:
        b = [int(p, 16) for p in parts]
    except ValueError:
        return None
    return b[0] | (b[1] << 8) | (b[2] << 16) | (b[3] << 24)


def _check_golden_decoding(mcinsns: list, pattern_fn) -> list:
    """For each :golden-bytes row, verify the bytes decode to the declared
    mcinsn via fixed-bit pattern matching.

    Two correctness conditions are checked:
      (1) The bytes themselves match the declared mcinsn's (mask, value).
          Failure means either the golden-bytes are wrong or the encoding
          spec doesn't agree with them.
      (2) The declared mcinsn is the *most-specific* match. If some other
          mcinsn has a strictly larger fixed_mask that also matches the
          bytes, a real prefix-match decoder would pick that one instead;
          the declared mcinsn must either be the most-specific match or
          share a documented overlap with it.

    Returns a list of (mcinsn_name, regs, hex_str, reason) tuples.
    """
    patterns = {insn.name: pattern_fn(insn) for insn in mcinsns}
    failures = []
    for insn in mcinsns:
        mask, value = patterns.get(insn.name, (0, 0))
        if mask == 0:
            continue
        popcount_self = bin(mask).count('1')
        for regs, hex_str in insn.golden_bytes:
            insn_bits = _golden_bytes_to_uint32(hex_str)
            if insn_bits is None:
                continue  # not a fixed-size 32-bit row
            if (insn_bits & mask) != value:
                failures.append((insn.name, regs, hex_str,
                                 f'bytes 0x{insn_bits:08x} & mask 0x{mask:08x} '
                                 f'= 0x{insn_bits & mask:08x}, expected fixed-value '
                                 f'0x{value:08x}'))
                continue
            # Find a strictly-more-specific match (larger fixed_mask popcount).
            for other_name, (o_mask, o_value) in patterns.items():
                if other_name == insn.name or o_mask == 0:
                    continue
                if bin(o_mask).count('1') <= popcount_self:
                    continue
                if (insn_bits & o_mask) != o_value:
                    continue
                # Some other mcinsn has a strictly tighter pattern that also
                # matches — declared mcinsn cannot be the disassembler winner.
                key = tuple(sorted((insn.name, other_name)))
                if key in _EXPECTED_ENCODING_OVERLAPS:
                    continue
                failures.append((insn.name, regs, hex_str,
                                 f'more-specific match: {other_name} '
                                 f'(mask 0x{o_mask:08x}) also matches'))
                break
    return failures


def cmd_disasm_check(args: list[str]):
    """Verify that no two mcinsns in the same arch have ambiguous fixed-bit
    patterns and that each :golden-bytes row decodes back to the declared
    mcinsn (prerequisites for any future disassembler / external diff).

    Usage: xisagen disasm-check arm64=<isa> riscv64=<isa> [...]"""
    if not args:
        die('usage: xisagen disasm-check arm64=<isa> riscv64=<isa> [...]')
    arch_patterns = {'arm64': _arm64_fixed_pattern, 'riscv64': _riscv64_fixed_pattern}
    total_pairs = 0
    total_ambig = 0
    total_golden = 0
    total_golden_fail = 0
    for spec in args:
        if '=' not in spec:
            die(f"expected arch=<isa>, got {spec!r}")
        arch, path = spec.split('=', 1)
        if arch not in arch_patterns:
            die(f"disasm-check: unsupported arch {arch!r} (supported: {sorted(arch_patterns)})")
        _regclasses, mcinsns = load_isa(path)
        pattern_fn = arch_patterns[arch]
        ambig = _check_fixed_uniqueness(mcinsns, pattern_fn)
        gold_fail = _check_golden_decoding(mcinsns, pattern_fn)
        n_pairs = len(mcinsns) * (len(mcinsns) - 1) // 2
        n_golden = sum(1 for m in mcinsns for _ in m.golden_bytes
                       if _golden_bytes_to_uint32(_[1]) is not None)
        total_pairs += n_pairs
        total_ambig += len(ambig)
        total_golden += n_golden
        total_golden_fail += len(gold_fail)
        print(f"xisagen disasm-check: {arch}: {len(mcinsns)} mcinsns, "
              f"{n_pairs} pairs, {len(ambig)} ambiguous; "
              f"{n_golden} 4-byte golden rows, {len(gold_fail)} mis-decoded",
              file=sys.stderr)
        for name_a, name_b, common, value in ambig:
            print(f"  AMBIGUOUS: {name_a} <-> {name_b}: "
                  f"common-fixed-mask=0x{common:08x} value=0x{value:08x}",
                  file=sys.stderr)
        for name, regs, hex_str, reason in gold_fail:
            print(f"  GOLDEN-DECODE-FAIL: {name} regs={regs} bytes='{hex_str}': {reason}",
                  file=sys.stderr)
    if total_ambig or total_golden_fail:
        die(f"disasm-check: {total_ambig} ambiguous pair(s), "
            f"{total_golden_fail} mis-decoded golden row(s)")
    print(f"xisagen disasm-check: ok ({total_pairs} pairs, {total_golden} golden rows "
          f"across {len(args)} arch(es))", file=sys.stderr)


