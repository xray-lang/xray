def cmd_isa(args: list[str]):
    if len(args) < 1:
        die("usage: xisagen.py isa <isa.isa> [output_dir]")
    path = args[0]
    output_dir = args[1] if len(args) > 1 else None
    regclasses, mcinsns = load_isa(path)
    arch = _detect_arch(mcinsns)
    print(f"xisagen: parsed {path}: {len(regclasses)} regclasses, {len(mcinsns)} mcinsns ({arch})",
          file=sys.stderr)

    # Validate golden bytes
    total_golden = sum(len(m.golden_bytes) for m in mcinsns)
    total_golden_asm = sum(len(m.golden_asm) for m in mcinsns)
    print(f"xisagen: {total_golden} golden-bytes, {total_golden_asm} golden-asm entries",
          file=sys.stderr)

    for insn in mcinsns:
        if insn.min_bytes <= 0:
            die(f"{path}: {insn.name}: missing :min-bytes")
        if insn.max_bytes < insn.min_bytes:
            die(f"{path}: {insn.name}: :max-bytes < :min-bytes")
        if not insn.golden_bytes:
            die(f"{path}: {insn.name}: no :golden-bytes")

    # Typecheck
    diags = typecheck_isa(regclasses, mcinsns)
    errors = [d for d in diags if d.level == 'error']
    warns = [d for d in diags if d.level == 'warn']
    for d in warns:
        print(f"xisagen: warn: {d.insn}: {d.msg}", file=sys.stderr)
    for d in errors:
        print(f"xisagen: error: {d.insn}: {d.msg}", file=sys.stderr)
    if errors:
        die(f"{len(errors)} typecheck error(s) in {path}")

    # Generate emit header if output_dir given
    if output_dir:
        header = generate_emit_header(arch, regclasses, mcinsns)
        out_path = os.path.join(output_dir, f'xisa_{arch}_emit.h')
        write_file(out_path, header)
        print(f"xisagen: generated {out_path}", file=sys.stderr)

